import { useState } from 'react';

/**
 * GPU kernels and the roofline model. A kernel is one function the GPU runs across thousands of threads at once. How
 * fast it can go is capped by whichever is slower: the arithmetic, or moving its data to and from memory. The ratio
 * of the two, arithmetic intensity (FLOPs per byte moved), says which cap applies. Every number here is computed from
 * the sliders with simple formulas, so it shows the shape of the limits, not a measured benchmark.
 */

const CHIPS = [
  { id: 'h100', name: 'NVIDIA H100 SXM', tflops: 989, gbs: 3350 },
  { id: 'b200', name: 'NVIDIA B200', tflops: 2250, gbs: 8000 },
  { id: 'm4', name: 'Apple M4 Max', tflops: 18, gbs: 546 },
];
const BYTES = 2; // bf16
const LAUNCH_US = 4; // a rough cost to start one kernel, in microseconds

const fmtTime = (s: number) => (s >= 1e-3 ? `${(s * 1e3).toFixed(2)} ms` : `${(s * 1e6).toFixed(1)} µs`);
const fmtBytes = (b: number) =>
  b >= 1e9 ? `${(b / 1e9).toFixed(2)} GB` : b >= 1e6 ? `${(b / 1e6).toFixed(1)} MB` : `${(b / 1e3).toFixed(0)} kB`;

/** Time for a kernel under the roofline: the slower of computing and moving data, plus its launch. */
function kernelTime(flops: number, bytes: number, tflops: number, gbs: number) {
  return Math.max(flops / (tflops * 1e12), bytes / (gbs * 1e9)) + LAUNCH_US * 1e-6;
}

// Log-log chart geometry.
const W = 560;
const H = 300;
const PAD = { l: 52, r: 16, t: 14, b: 40 };
const X_MIN = 0.1;
const X_MAX = 10000;

export default function Kernels() {
  const [chipId, setChipId] = useState('h100');
  const [tokens, setTokens] = useState(1);
  const [hidden, setHidden] = useState(4096);
  const [ops, setOps] = useState(4);
  const [seq, setSeq] = useState(8192);
  const chip = CHIPS.find((c) => c.id === chipId)!;
  const ridge = (chip.tflops * 1e12) / (chip.gbs * 1e9);
  const yMax = chip.tflops * 1.6;
  const yMin = chip.tflops / 20000;
  const x = (ai: number) =>
    PAD.l + ((Math.log10(ai) - Math.log10(X_MIN)) / (Math.log10(X_MAX) - Math.log10(X_MIN))) * (W - PAD.l - PAD.r);
  const y = (tf: number) =>
    PAD.t + (1 - (Math.log10(tf) - Math.log10(yMin)) / (Math.log10(yMax) - Math.log10(yMin))) * (H - PAD.t - PAD.b);
  const attainable = (ai: number) => Math.min(chip.tflops, (ai * chip.gbs * 1e9) / 1e12);

  // A matrix multiply: (tokens × hidden) by (hidden × hidden), the shape of one linear layer.
  const mmFlops = 2 * tokens * hidden * hidden;
  const mmBytes = BYTES * (tokens * hidden + hidden * hidden + tokens * hidden);
  const mmAI = mmFlops / mmBytes;
  // An element-wise op (an add, or GELU) on the same activations: a few FLOPs per value, one read and one write.
  const ewAI = 4 / (2 * BYTES);
  const points = [
    { label: `Linear layer, ${tokens} token${tokens === 1 ? '' : 's'}`, ai: mmAI, cls: 'mm' },
    { label: 'Element-wise op', ai: ewAI, cls: 'ew' },
  ];

  // Fusion: a chain of element-wise ops on tokens × hidden activations. Unfused, each op reads and writes the whole
  // tensor and launches its own kernel; fused, the data is read once, every op runs in registers, then written once.
  const elems = Math.max(1, tokens) * hidden * 64; // 64 layers' worth, so the times are visible
  const unfusedBytes = ops * 2 * elems * BYTES;
  const fusedBytes = 2 * elems * BYTES;
  const unfused = ops * kernelTime(4 * elems, 2 * elems * BYTES, chip.tflops, chip.gbs);
  const fused = kernelTime(4 * ops * elems, fusedBytes, chip.tflops, chip.gbs);

  // Attention for one head of size 128: the plain version writes the seq × seq score matrix to memory and reads it
  // back (scores, then probabilities); a tiled version keeps those tiles in on-chip memory and never writes them.
  const d = 128;
  const qkvo = 4 * seq * d * BYTES;
  const plainBytes = qkvo + 4 * seq * seq * BYTES;
  const tiledBytes = qkvo;
  const attnFlops = 4 * seq * seq * d;
  const plainTime = kernelTime(attnFlops, plainBytes, chip.tflops, chip.gbs);
  const tiledTime = kernelTime(attnFlops, tiledBytes, chip.tflops, chip.gbs);
  const widest = Math.max(unfused, fused);
  const widestAttn = Math.max(plainTime, tiledTime);

  const ticksX = [0.1, 1, 10, 100, 1000, 10000];
  const ticksY = [0.01, 0.1, 1, 10, 100, 1000].filter((t) => t >= yMin && t <= yMax);

  return (
    <section className="card hw-kernels">
      <h2>Kernels: why some GPU work waits on memory</h2>
      <p>
        A kernel is one function a GPU runs over thousands of threads at once: a matrix multiply, a softmax, an
        element-wise add. Written in CUDA or Triton, or generated by a compiler, each kernel reads its inputs from the
        GPU’s main memory (HBM), computes, and writes its result back. Its speed is capped by the slower of the two. The
        roofline below shows the cap: on the left, memory decides (the sloped line); right of the ridge, arithmetic does
        (the flat line). Where a kernel sits depends on its arithmetic intensity, the FLOPs it does per byte it moves.
      </p>
      <div className="hw-k-controls">
        <label>
          Chip{' '}
          <select value={chipId} onChange={(e) => setChipId(e.target.value)}>
            {CHIPS.map((c) => (
              <option key={c.id} value={c.id}>
                {c.name}
              </option>
            ))}
          </select>
        </label>
        <label>
          Tokens processed together <b>{tokens}</b>
          <input
            type="range"
            min={0}
            max={12}
            step={1}
            value={Math.log2(tokens)}
            onChange={(e) => setTokens(2 ** Number(e.target.value))}
          />
        </label>
        <label>
          Hidden size
          <select value={hidden} onChange={(e) => setHidden(Number(e.target.value))}>
            {[1024, 4096, 8192].map((h) => (
              <option key={h}>{h}</option>
            ))}
          </select>
        </label>
      </div>
      <svg viewBox={`0 0 ${W} ${H}`} className="hw-roofline" role="img" aria-label="Roofline chart">
        {ticksX.map((t) => (
          <g key={`x${t}`}>
            <line x1={x(t)} x2={x(t)} y1={PAD.t} y2={H - PAD.b} className="grid" />
            <text x={x(t)} y={H - PAD.b + 16} textAnchor="middle">
              {t}
            </text>
          </g>
        ))}
        {ticksY.map((t) => (
          <g key={`y${t}`}>
            <line x1={PAD.l} x2={W - PAD.r} y1={y(t)} y2={y(t)} className="grid" />
            <text x={PAD.l - 6} y={y(t) + 4} textAnchor="end">
              {t}
            </text>
          </g>
        ))}
        <text x={(W + PAD.l) / 2} y={H - 4} textAnchor="middle" className="axis">
          FLOPs per byte moved (log)
        </text>
        <text
          x={12}
          y={(H - PAD.b) / 2}
          transform={`rotate(-90 12 ${(H - PAD.b) / 2})`}
          textAnchor="middle"
          className="axis"
        >
          TFLOP/s (log)
        </text>
        <polyline
          className="roof"
          points={[X_MIN, ridge, X_MAX].map((ai) => `${x(ai)},${y(attainable(ai))}`).join(' ')}
        />
        <line x1={x(ridge)} x2={x(ridge)} y1={y(chip.tflops)} y2={H - PAD.b} className="ridge" />
        <text x={x(ridge) + 4} y={H - PAD.b - 6} className="ridge-label">
          ridge {ridge.toFixed(0)}
        </text>
        {points.map((p) => (
          <g key={p.cls}>
            <circle
              cx={x(Math.min(X_MAX, Math.max(X_MIN, p.ai)))}
              cy={y(attainable(p.ai))}
              r={6}
              className={`pt ${p.cls}`}
            />
            <text
              x={x(Math.min(X_MAX, Math.max(X_MIN, p.ai))) + 9}
              y={y(attainable(p.ai)) + (p.cls === 'ew' ? 20 : -8)}
              className={`pt-label ${p.cls}`}
            >
              {p.label}
            </text>
          </g>
        ))}
      </svg>
      <p className="small">
        The linear layer does {mmAI.toFixed(1)} FLOPs per byte, so at most{' '}
        <b>{attainable(mmAI).toFixed(attainable(mmAI) < 10 ? 2 : 0)} TFLOP/s</b> of the {chip.name}’s {chip.tflops}:{' '}
        {mmAI < ridge
          ? `memory-bound. With one token, every weight is read to do two FLOPs with it, which is why generating text one token at a time is limited by memory speed. Process more tokens together and the same weights are reused, so the dot climbs the slope.`
          : `compute-bound. Enough tokens share each weight that the arithmetic, not memory, is now the limit.`}{' '}
        The ridge sits at {ridge.toFixed(0)} FLOPs per byte: a kernel needs at least that much reuse to keep this chip’s
        arithmetic busy.
      </p>

      <h3>Fusing kernels: move the data once</h3>
      <p className="small">
        Element-wise ops do almost no arithmetic per byte, so they always sit far down the slope. A chain of them (bias,
        activation, scaling, a residual add) run as separate kernels reads and writes the whole tensor each time. Fused
        into one kernel, the data is read once, every op runs in the chip’s registers, and the result is written once.
        The FLOPs are the same; the memory traffic is not.
      </p>
      <div className="hw-k-controls">
        <label>
          Ops in the chain <b>{ops}</b>
          <input type="range" min={2} max={8} value={ops} onChange={(e) => setOps(Number(e.target.value))} />
        </label>
      </div>
      <div className="hw-k-bars">
        <div>
          <span>Separate kernels</span>
          <i style={{ width: `${(unfused / widest) * 100}%` }} className="slow" />
          <span className="mono">
            {fmtTime(unfused)} · {fmtBytes(unfusedBytes)} moved
          </span>
        </div>
        <div>
          <span>One fused kernel</span>
          <i style={{ width: `${(fused / widest) * 100}%` }} className="fast" />
          <span className="mono">
            {fmtTime(fused)} · {fmtBytes(fusedBytes)} moved
          </span>
        </div>
      </div>

      <h3>Tiled attention: never write the big matrix</h3>
      <p className="small">
        Attention compares every token with every other, making a sequence × sequence matrix of scores. Done plainly,
        that matrix is written to memory, read back for the softmax, written again and read again for the weighted sum.
        Tiled attention (FlashAttention is the best-known version) works on blocks small enough to stay in on-chip
        memory and keeps a running softmax, so the big matrix never reaches main memory. Same result, far fewer bytes
        moved, and memory use that grows with the sequence rather than its square.
      </p>
      <div className="hw-k-controls">
        <label>
          Sequence length <b>{seq.toLocaleString('en-GB')}</b>
          <input
            type="range"
            min={9}
            max={17}
            value={Math.log2(seq)}
            onChange={(e) => setSeq(2 ** Number(e.target.value))}
          />
        </label>
      </div>
      <div className="hw-k-bars">
        <div>
          <span>Plain attention</span>
          <i style={{ width: `${(plainTime / widestAttn) * 100}%` }} className="slow" />
          <span className="mono">
            {fmtTime(plainTime)} · {fmtBytes(plainBytes)} moved
          </span>
        </div>
        <div>
          <span>Tiled attention</span>
          <i style={{ width: `${(tiledTime / widestAttn) * 100}%` }} className="fast" />
          <span className="mono">
            {fmtTime(tiledTime)} · {fmtBytes(tiledBytes)} moved
          </span>
        </div>
      </div>
      <p className="small muted">
        One attention head of size 128 in bf16, timed by the roofline alone with a {LAUNCH_US} µs launch cost. Real
        kernels lose time to things this leaves out (caches, scheduling, partly filled tiles), so read these as the
        shape of the limits, not benchmarks. Writing fast kernels is specialist work; most teams get these gains from
        libraries and compilers that already fuse and tile.
      </p>
    </section>
  );
}
